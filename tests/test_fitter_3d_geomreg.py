"""Tests of the closed-form native start and the native refit (numpy only: no GPU, no scan, no truth, no network):
the start is a set of fitter_3d native parameters that reproduces the joints it was built from (pivot and medial
joints), and the refit recovers parameters with three scales per bone.

pytest tests/test_fitter_3d_geomreg.py        (from the repository root; CPU)
"""

import os
import sys

import numpy as np
import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from fitter_3d.geomreg import native, refit
from fitter_3d.geomreg.model import template

PKL = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "3D_model_prep", "OmniAnt_25PCs_joint_limited.pkl"
)
pytestmark = pytest.mark.skipif(not os.path.isfile(PKL), reason="model pkl not found")


@pytest.fixture(scope="module")
def tpl():
    return template(PKL)


def random_params(tpl, rng, aniso=False, pose=0.5, scale=0.25):
    """native parameters of a random posed, scaled individual (rotations inside the joint limits)"""
    nJ = tpl.nJ
    lo, hi = tpl.limits[1:, :, 0], tpl.limits[1:, :, 1]
    jr = np.clip(rng.normal(0, pose, (nJ - 1, 3)), lo, hi)
    lbs = np.zeros((nJ, 3))
    if aniso:
        lbs[1:] = rng.normal(0, scale, (nJ - 1, 3))
    else:
        lbs[1:] = rng.normal(0, scale, (nJ - 1, 1))
    return dict(
        global_rot=rng.normal(0, 0.8, 3),
        joint_rot=jr,
        betas=np.zeros(tpl.nB),
        log_beta_scales=lbs,
        trans=rng.normal(0, 0.3, 3),
        betas_trans=np.zeros((nJ, 3)),
        log_scale=np.array([rng.normal(0, 0.3)]),
        rotation_mask=np.ones((nJ - 1, 3)),
    )


def targets_of(tpl, V, piv, kind):
    P = (tpl.marker_regressor() @ V) if kind == "medial" else piv.copy()
    w = np.ones(tpl.nJ)
    for j, n in enumerate(tpl.names):
        if n.startswith("w_") or (kind == "medial" and n == "b_t"):
            w[j] = 0.0
    return P, w


def start_of(tpl, V, piv, kind, drop=(), **kw):
    P, w = targets_of(tpl, V, piv, kind)
    for n in drop:
        w[tpl.idx[n]] = 0.0
    P = P.copy()
    P[w <= 0] = np.nan
    mk = tpl.marker_regressor() @ V
    BL = native.chord_body_length(tpl, mk, tpl.head_front_row() @ V)
    return native.closed_form_start(tpl, P, w, kind=kind, R_prior=kw.pop("R_prior", np.eye(3)), BL=BL, **kw), P, w


@pytest.mark.parametrize("kind", ["pivot", "medial"])
def test_start_is_a_native_parameter_set(tpl, kind):
    """forward(to_native(start)) == the closed-form blend of the bone maps, and every usable joint of a
    joint-supported chain is reproduced"""
    rng = np.random.default_rng(1)
    V, piv = native.forward_np(tpl, random_params(tpl, rng))
    st, P, w = start_of(tpl, V, piv, kind)
    p = native.to_native(st)
    Vf, pivf = native.forward_np(tpl, p)
    assert np.abs(Vf - st.vertices()).max() < 1e-9
    assert np.allclose(p["log_beta_scales"][0], 0.0)  # the root scale must stay 0
    assert np.allclose(p["log_beta_scales"], p["log_beta_scales"][:, :1])  # isotropic per bone
    ref = pivf if kind == "pivot" else tpl.marker_regressor() @ Vf
    chain = [j for j in range(tpl.nJ) if st.how[j] == "chain"]
    assert len(chain) >= 30
    err = np.linalg.norm(ref[chain] - P[chain], axis=1)
    tol = 1e-9 if kind == "pivot" else 0.02 * np.ptp(V, 0).max()  # marker rings are blended over > 2 bones
    assert err.max() < tol


def test_refit_recovers_native_parameters(tpl):
    """a mesh generated by the model with THREE scales per bone is reproduced by the refit with a small residual,
    and the written parameters reproduce the fitted maps exactly"""
    rng = np.random.default_rng(6)
    p_true = random_params(tpl, rng, aniso=True, pose=0.4, scale=0.15)
    V, piv = native.forward_np(tpl, p_true)
    st, P, w = start_of(tpl, V, piv, "pivot")
    p0 = native.to_native(st)
    d0 = np.linalg.norm(native.forward_np(tpl, p0)[0] - V, axis=1)
    p, info = refit.native_refit(tpl, V, np.ones(tpl.nV, bool), p0, BL=1.0, sweeps=10)
    d1 = np.linalg.norm(native.forward_np(tpl, p)[0] - V, axis=1)
    ext = np.ptp(V, 0).max()
    assert info["native_vs_maps_max"] < 1e-9
    assert np.median(d1) < 0.25 * np.median(d0)
    assert np.median(d1) < 0.003 * ext
